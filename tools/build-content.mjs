// Writes the static art map, the English night-step text and the locale registry under
// src/content/generated/, since Metro bundles only what it can see. `--check` writes nothing and fails when the tree is stale.
// Run from the repository root.
import { readdirSync, readFileSync, writeFileSync, existsSync, statSync } from 'node:fs'
import { join, relative, basename, sep } from 'node:path'

const root = process.cwd()
const check = process.argv.includes('--check')
const out = join(root, 'src', 'content', 'generated')

const header = '// Generated by tools/build-content.mjs. Do not edit; run `npm run content`.\n'

const walk = (dir) =>
  readdirSync(dir).flatMap((name) => {
    const p = join(dir, name)
    return statSync(p).isDirectory() ? walk(p) : [p]
  })

const posix = (p) => p.split(sep).join('/')

// The art map. A character icon is `<id>.webp`, or `<id>_g.webp` and `<id>_e.webp` where
// upstream draws both tints. Everything else under assets/art is keyed by its file name.
const art = () => {
  const artRoot = join(root, 'assets', 'art')
  const req = (f) => `require('../../../${posix(relative(root, f))}')`
  const icons = {}
  for (const f of walk(join(artRoot, 'characters')).sort()) {
    const m = basename(f, '.webp').match(/^(.*?)(?:_([ge]))?$/)
    const id = m[1]
    const tint = m[2]
    icons[id] ??= {}
    icons[id][tint === 'g' ? 'good' : tint === 'e' ? 'evil' : 'single'] = req(f)
  }
  const flat = (sub) =>
    walk(join(artRoot, sub))
      .sort()
      .filter((f) => /\.(webp|png)$/.test(f))
      .map((f) => `  ${JSON.stringify(basename(f).replace(/\.\w+$/, ''))}: ${req(f)},`)
      .join('\n')
  const iconLines = Object.entries(icons)
    .map(([id, t]) => `  ${JSON.stringify(id)}: { ${Object.entries(t).map(([k, v]) => `${k}: ${v}`).join(', ')} },`)
    .join('\n')
  return `${header}
// Expo's web bundler exports static images as URI objects in development and in the export.
export interface CharacterImage {
  readonly uri: string
  readonly width: number
  readonly height: number
}

export interface CharacterArt {
  readonly single?: CharacterImage
  readonly good?: CharacterImage
  readonly evil?: CharacterImage
}

export const characterArt: Readonly<Record<string, CharacterArt>> = {
${iconLines}
}

export const editionArt: Readonly<Record<string, number>> = {
${flat('editions')}
}

export const genericArt: Readonly<Record<string, number>> = {
${flat('generic')}
}

export const tokenArt: Readonly<Record<string, CharacterImage>> = {
${flat('tokens')}
}

export const communityArt: Readonly<Record<string, number>> = {
${flat('community')}
}
`
}

// The English instructions for the night sheet's steps that are not characters. They are all the
// app needs from upstream's English translation, whose names and abilities repeat roles.json, so
// the whole file stays out of the bundle.
const nightText = () => {
  const read = (...p) => JSON.parse(readFileSync(join(root, 'assets', 'data', 'raw', ...p), 'utf8'))
  const roles = new Set(read('release', 'roles.json').map((r) => r.id))
  const sheet = read('release', 'nightsheet.json')
  const english = read('translations', 'game', 'en.json').roles
  const steps = [...new Set([...sheet.firstNight, ...sheet.otherNight])].filter((id) => !roles.has(id)).sort()
  const lines = steps
    .map((id) => {
      const { first, other } = english[id] ?? {}
      return `  ${JSON.stringify(id)}: ${JSON.stringify({ first, other })},`
    })
    .join('\n')
  return `${header}
export const englishNightText: Readonly<Record<string, { readonly first?: string; readonly other?: string }>> = {
${lines}
}
`
}

// The locale registry. Every folder under src/content/locales is a UI language, named by its
// BCP 47 tag; its game text is upstream's file of the same name with `_` for `-` (nb-NO is
// nb_NO.json), when one is bundled. English game text comes from roles.json instead. Languages
// are listed by their own names, as a language picker lists them.
const localeRegistry = () => {
  const uiRoot = join(root, 'src', 'content', 'locales')
  const gameRoot = join(root, 'assets', 'data', 'raw', 'translations', 'game')
  const ident = (tag) => tag.replace(/-/g, '_')
  const name = (tag) => JSON.parse(readFileSync(join(uiRoot, tag, 'common.json'), 'utf8')).localeName ?? tag
  const tags = readdirSync(uiRoot)
    .filter((tag) => statSync(join(uiRoot, tag)).isDirectory())
    .sort((a, b) => name(a).localeCompare(name(b), 'en') || a.localeCompare(b))
  const areas = (tag) => readdirSync(join(uiRoot, tag)).filter((f) => f.endsWith('.json')).map((f) => basename(f, '.json')).sort()
  const game = tags.filter((tag) => tag !== 'en' && existsSync(join(gameRoot, `${ident(tag)}.json`)))
  const imports = [
    ...tags.flatMap((tag) => areas(tag).map((a) => `import ${ident(tag)}_${a} from '../locales/${tag}/${a}.json'`)),
    ...game.map((tag) => `import ${ident(tag)}_game from '../../../assets/data/raw/translations/game/${ident(tag)}.json'`),
  ].join('\n')
  const ui = tags.map((tag) => `  ${JSON.stringify(tag)}: { ${areas(tag).map((a) => `${a}: ${ident(tag)}_${a}`).join(', ')} },`).join('\n')
  const gameLines = game.map((tag) => `  ${JSON.stringify(tag)}: ${ident(tag)}_game,`).join('\n')
  return `${header}${imports}

export const locales = ${JSON.stringify(tags)} as const

export const uiText = {
${ui}
} as const

export const gameTranslations = {
${gameLines}
} as const
`
}

const files = { 'art.ts': art(), 'nightText.ts': nightText(), 'locales.ts': localeRegistry() }
let stale = 0
for (const [name, content] of Object.entries(files)) {
  const p = join(out, name)
  const current = existsSync(p) ? readFileSync(p, 'utf8') : ''
  if (current === content) continue
  if (check) {
    console.error(`stale: ${posix(relative(root, p))}`)
    stale++
  } else {
    writeFileSync(p, content)
    console.log(`wrote ${posix(relative(root, p))}`)
  }
}
if (check && stale) {
  console.error('run `npm run content` to regenerate them')
  process.exit(1)
}
if (check) console.log('generated files are fresh')
